(function(){
  var html = document.documentElement;
  var switches = document.querySelectorAll('[data-lang]');
  var defaultLang = html.getAttribute('lang') || 'fr';

  function apply(lang){
    var dict = I18N[lang] || I18N.fr;
    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var key = el.getAttribute('data-i18n');
      if(dict[key]){
        if(dict[key].indexOf('<')!==-1) el.innerHTML = dict[key];
        else el.textContent = dict[key];
      }
    });
    // also handle placeholders and options via data-i18n-placeholder / data-i18n-options
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
      var key = el.getAttribute('data-i18n-placeholder');
      if(dict[key]) el.setAttribute('placeholder', dict[key]);
    });
    // select options
    document.querySelectorAll('select[data-i18n-options]').forEach(function(sel){
      var base = sel.getAttribute('data-i18n-options');
      Array.from(sel.options).forEach(function(opt, idx){
        var k = base + '.' + idx;
        if(dict[k]) opt.textContent = dict[k];
      });
    });
    html.setAttribute('lang', lang);
    html.setAttribute('dir', lang==='ar' ? 'rtl' : 'ltr');
    switches.forEach(function(a){
      a.classList.toggle('active', a.getAttribute('data-lang')===lang);
    });
    try{ if(!location.search.includes('preview=1')){ localStorage.setItem('taourirt_lang', lang); document.cookie='taourirt_lang='+lang+';path=/;max-age=31536000;SameSite=Lax'; } }catch(e){}
    // dispatch event for pages that have dynamic address/hours
    document.dispatchEvent(new CustomEvent('taourirt:langchange', {detail:{lang:lang}}));
  }

  switches.forEach(function(a){
    a.addEventListener('click', function(e){
      e.preventDefault();
      apply(a.getAttribute('data-lang'));
    });
  });

  // restore or default french — preview respects URL lang, not localStorage
  try{
    var urlLang = new URLSearchParams(location.search).get('lang');
    if(urlLang && I18N[urlLang] && location.search.includes('lang=')){
      defaultLang = urlLang;
    } else {
      var saved = localStorage.getItem('taourirt_lang');
      if(saved && I18N[saved]) defaultLang = saved;
    }
  }catch(e){}
  apply(defaultLang);

  // expose for admin later
  window.__applyLang = apply;
})();

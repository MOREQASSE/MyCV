let currentLang = 'en';

function changeLanguage(lang) {
    currentLang = lang;
    document.getElementById('current-lang').querySelector('span').textContent = lang.toUpperCase();
    
    // Update active state in dropdown
    document.querySelectorAll('.lang-option').forEach(function (opt) {
        opt.classList.toggle('active', opt.dataset.lang === lang);
    });

    // Close dropdown
    var switcher = document.getElementById('language-switcher');
    if (switcher) switcher.classList.remove('open');

    // Update all translatable elements
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[lang][key]) {
            element.innerHTML = translations[lang][key];
        }
    });

    // Update placeholders
    document.querySelectorAll('[data-translate-placeholder]').forEach(element => {
        const key = element.getAttribute('data-translate-placeholder');
        if (translations[lang][key]) {
            element.placeholder = translations[lang][key];
        }
    });

    // Update HTML lang attribute
    document.documentElement.lang = lang;
    
    // RTL support for Arabic
    if (lang === 'ar') {
        document.documentElement.dir = 'rtl';
        document.body.style.fontFamily = "'Inter', 'Segoe UI', 'Tahoma', sans-serif";
    } else {
        document.documentElement.dir = 'ltr';
        document.body.style.fontFamily = "'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif";
    }

    // Save preference
    localStorage.setItem('preferredLanguage', lang);

    // Re-render web portfolio carousel in new language
    if (window.rerenderWebPortfolio) window.rerenderWebPortfolio();

    // Update wheel timeline detail panel in new language
    if (window.updateWheelTimelineLang) window.updateWheelTimelineLang();
}

